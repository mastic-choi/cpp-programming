#include <iostream>

int main() {
    // ---------------------------------------------------------
    // [미션 1] 단일 변수 동적 할당과 값 넣기
    // ---------------------------------------------------------
    std::cout << "--- [미션 1] ---" << std::endl;
    
    // TODO 1: C++의 'new' 키워드를 사용하여 정수형(int) 데이터를 담을 수 있는 
    // 메모리 공간 1칸을 빌리고, 그 시작 주소를 포인터 변수 'single_ptr'에 저장하세요.
    // (이곳에 코드 작성)
    int* single_ptr = new int;

    // TODO 2: 역참조 연산자(*)를 사용하여, 방금 빌린 공간에 직접 쳐들어가서 숫자 77을 넣으세요.
    // (이곳에 코드 작성)
    
    *single_ptr = 77;

    // 아래 주석을 풀고 실행했을 때 77이 나와야 성공입니다.
    std::cout << "단일 변수에 들어간 값: " << *single_ptr << " (77이 나와야 성공!)" << std::endl;


    // ---------------------------------------------------------
    // [미션 2] 단일 변수 메모리 반납
    // ---------------------------------------------------------
    std::cout << "\n--- [미션 2] ---" << std::endl;
    // TODO 3: C++의 올바른 반납 키워드를 사용하여 'single_ptr'이 가리키는 땅을 반납하세요.
    // 주의: 절대 free를 쓰지 마세요!
    delete single_ptr;
    
    std::cout << "단일 변수 메모리 안전하게 반납 완료!" << std::endl;


    // ---------------------------------------------------------
    // [미션 3] 배열 동적 할당 (여러 칸 한 번에 빌리기)
    // ---------------------------------------------------------
    std::cout << "\n--- [미션 3] ---" << std::endl;
    int n = 5; 

    // TODO 4: 'new' 키워드를 사용하여 크기가 'n'인 정수형 배열(5칸짜리) 메모리를 빌리고,
    // 그 시작 주소를 포인터 변수 'arr_ptr'에 저장하세요.
    int* arr_ptr = new int[n];
    

    // 아래 주석을 풀고 실행했을 때 20이 나와야 성공입니다.
    for(int i = 0; i < n; i++) { arr_ptr[i] = i * 10; }
    std::cout << "배열의 3번째 칸 값: " << arr_ptr[4] << " (20이 나와야 성공!)" << std::endl;


    // ---------------------------------------------------------
    // [미션 4] 배열 메모리 전용 반납
    // ---------------------------------------------------------
    std::cout << "\n--- [미션 4] ---" << std::endl;
    
    // TODO 5: 'arr_ptr' 배열의 메모리를 반납하세요.
    // 아주 중요한 규칙: 배열을 반납할 때는 해제 키워드 바로 뒤에 '특수한 괄호 기호'를 반드시 붙여야 합니다! [1]
    delete[] arr_ptr;    
    std::cout << "배열 메모리 안전하게 반납 완료!" << std::endl;

    return 0;
}