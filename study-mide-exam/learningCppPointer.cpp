#include<iostream>
#include<string>


void doubleGold(int* value){
    *value *= 2;
}


typedef struct{
    int pwd;
}Chest;

int main() {
    // ---------------------------------------------------------
    // [미션 1] 변수의 주소와 포인터 변수 저장하기
    // ---------------------------------------------------------
    std::cout << "--- [미션 1] ---" << std::endl;
    int gold = 100; 
    
    // TODO: 변수 gold가 살고 있는 '메모리 주소'를 알아내서, 
    // 그것을 저장할 수 있는 포인터 변수 'ptr_gold'를 선언하고 저장하세요.
    int* ptr_gold = new int;
    ptr_gold = &gold;
    doubleGold(ptr_gold);
    

    // 아래 주석을 풀고 실행했을 때, 두 줄에 똑같은 형태의 메모리 주소(예: 0x7fff...)가 나와야 성공입니다! [1]
    std::cout << "gold의 진짜 위치: " << &gold << std::endl;
    std::cout << "ptr_gold가 기억하는 위치: " << ptr_gold << std::endl;


    // ---------------------------------------------------------
    // [미션 2] 역참조 연산자 - "그 주소로 찾아가라!"
    // ---------------------------------------------------------

    // TODO: 이번 줄에서는 'gold'라는 단어를 절대 쓰지 마세요!
    // 오직 방금 만든 'ptr_gold'만을 사용하여, 그 주소로 직접 쳐들어가서 원본 값을 999로 바꿔버리세요. [1, 2]
    std::cout << "\n--- [미션 2] ---" << std::endl;
    *ptr_gold = 999;
    std::cout << "변경된 gold의 값: " << gold << " (999가 나와야 성공!)" << std::endl;


    // ---------------------------------------------------------
    // [미션 3] 함수에 주소 넘기기 (Call by Pointer)
    // ---------------------------------------------------------
    std::cout << "\n--- [미션 3] ---" << std::endl;
    int myScore = 50;
    
    // TODO: 위에서 만든 doubleGold 함수를 호출하세요.
    // 주의: 지역 복사본이 넘어가지 않도록, myScore의 '주소'를 함수로 던져주어야 원본이 2배가 됩니다! [2]
    // (이곳에 코드 작성)
    doubleGold(&myScore);
    std::cout << "함수 실행 후 내 점수: " << myScore << " (100이 나와야 성공!)" << std::endl;


    // ---------------------------------------------------------
    // [미션 4] 구조체와 포인터 
    // ---------------------------------------------------------
    std::cout << "\n--- [미션 4] ---" << std::endl;
    
    // 1. Chest 구조체 변수 'box'를 만들고, pwd를 1234로 설정하세요.
    // (이곳에 코드 작성)
    Chest box;
    box.pwd = 1234;
    
    // 2. 이 box의 '주소'를 저장하는 구조체 포인터 변수 'ptr_box'를 만드세요.
    // (이곳에 코드 작성)
    Chest* ptr_box = new Chest;
    ptr_box = &box;

    // 3. TODO: 'box'라는 단어는 쓰지 말고, 오직 'ptr_box'만을 사용하여 pwd를 7777로 바꾸세요.
    // 힌트 금지 규칙에 따라 기호를 직접 알려드릴 순 없지만, 포인터가 구조체를 가리킬 때는 점(.)이 아니라 '특수한 모양의 기호'를 씁니다! [3]
    // (이곳에 코드 작성)
    ptr_box->pwd = 7777; 

    // 아래 주석을 풀었을 때 7777이 나오면 최종 성공입니다.
    std::cout << "변경된 상자의 비밀번호: " << box.pwd << " (7777이 나와야 성공!)" << std::endl;

    return 0;
}